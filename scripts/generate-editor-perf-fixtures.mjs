/**
 * Writes the `D-015` performance fixtures and pins their checksums.
 *
 * The fixture bytes are *not* committed. They are 1.1 MiB of generated text
 * whose only job is to be reproducible, and a checksum pin does that job with
 * 1 KiB instead: `scripts/editor-perf-fixture.mjs` is pure and seeded, so any
 * machine that runs this script produces the same bytes, and this script
 * refuses to finish if it does not. What is committed is the pin —
 * `docs/loopx/design/2026-08-12-milkdown-editor-migration/P-007-fixture-checksums.json` —
 * which is what a measurement artifact is tied to.
 *
 * Usage:
 *   node scripts/generate-editor-perf-fixtures.mjs           write + verify pin
 *   node scripts/generate-editor-perf-fixtures.mjs --check   verify pin, no write
 *   node scripts/generate-editor-perf-fixtures.mjs --update   rewrite the pin
 *
 * Exits non-zero when the generated bytes do not match the pin, which is the
 * signal that either the generator changed or the pin is stale. Both are
 * measurement-invalidating events and neither may pass quietly.
 */

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
    EDITOR_PERF_FIXTURES,
    fixtureSyntaxProfile,
    generateEditorPerfFixture,
} from "./editor-perf-fixture.mjs";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_DIR = join(REPO_ROOT, "artifacts", "editor-perf", "fixtures");
const PIN_PATH = join(
    REPO_ROOT,
    "docs",
    "loopx",
    "design",
    "2026-08-12-milkdown-editor-migration",
    "P-007-fixture-checksums.json",
);

/** Same digest the harness computes in the page, so the two can be compared. */
export function sha256Hex(text) {
    return createHash("sha256").update(text, "utf8").digest("hex");
}

/**
 * Every syntax family the fixture is required to exercise, and the minimum
 * number of occurrences that counts as exercising it.
 *
 * A fixture that lost a family — because a weight was edited, or a construct
 * stopped being emitted — would still be the right size and still produce a
 * stable checksum, and would still be a reduced-syntax fixture, which `D-015`
 * forbids. This is the check that notices.
 */
const REQUIRED_FAMILIES = {
    frontmatter: 1,
    headings: 10,
    callouts: 10,
    mermaidFences: 4,
    codeFences: 10,
    blockMath: 5,
    inlineMath: 30,
    footnoteCalls: 10,
    footnoteDefinitions: 5,
    wikilinks: 30,
    links: 30,
    htmlBlocks: 4,
    inlineHtml: 10,
    directives: 4,
    tableRows: 30,
    listItems: 50,
    taskItems: 10,
    thematicBreaks: 1,
    emoji: 10,
    cjkCharacters: 500,
};

function buildFixtures() {
    return EDITOR_PERF_FIXTURES.map((descriptor) => {
        const text = generateEditorPerfFixture({
            seed: descriptor.seed,
            targetBytes: descriptor.bytes,
        });
        const profile = fixtureSyntaxProfile(text);
        return {
            id: descriptor.id,
            seed: descriptor.seed,
            file: `${descriptor.id}.md`,
            bytes: profile.bytes,
            sha256: sha256Hex(text),
            profile,
            text,
        };
    });
}

/** Rejects a fixture that is the right size but no longer mixed-syntax. */
function assertMixedSyntax(fixture) {
    const missing = [];
    for (const [family, minimum] of Object.entries(REQUIRED_FAMILIES)) {
        const found = fixture.profile[family] ?? 0;
        if (found < minimum) missing.push(`${family}=${String(found)} (need ${String(minimum)})`);
    }
    if (missing.length > 0) {
        throw new Error(
            `fixture ${fixture.id} is not mixed-syntax: ${missing.join(", ")}`,
        );
    }
}

/** Proves determinism here rather than asserting it: generate twice, compare. */
function assertDeterministic(fixture) {
    const again = generateEditorPerfFixture({
        seed: fixture.seed,
        targetBytes: fixture.bytes,
    });
    if (sha256Hex(again) !== fixture.sha256) {
        throw new Error(`fixture ${fixture.id} is not deterministic within one process`);
    }
}

function readPin() {
    try {
        return JSON.parse(readFileSync(PIN_PATH, "utf8"));
    } catch {
        return null;
    }
}

function pinDocument(fixtures) {
    return {
        contract: "D-015",
        generator: "scripts/editor-perf-fixture.mjs",
        note: "Fixture bytes are generated, not committed. Regenerate with `npm run fixtures:editor:perf`; verify with `npm run fixtures:editor:perf:check`.",
        fixtures: fixtures.map((fixture) => ({
            id: fixture.id,
            seed: fixture.seed,
            bytes: fixture.bytes,
            sha256: fixture.sha256,
            syntaxProfile: fixture.profile,
        })),
    };
}

function comparePin(fixtures, pin) {
    if (pin === null) {
        return [`no checksum pin at ${PIN_PATH}; run with --update to create it`];
    }
    const failures = [];
    const pinned = new Map((pin.fixtures ?? []).map((entry) => [entry.id, entry]));
    for (const fixture of fixtures) {
        const entry = pinned.get(fixture.id);
        if (entry === undefined) {
            failures.push(`fixture ${fixture.id} is not in the pin`);
            continue;
        }
        if (entry.bytes !== fixture.bytes) {
            failures.push(
                `fixture ${fixture.id} is ${String(fixture.bytes)} bytes; pin says ${String(entry.bytes)}`,
            );
        }
        if (entry.sha256 !== fixture.sha256) {
            failures.push(
                `fixture ${fixture.id} sha256 ${fixture.sha256} does not match pinned ${String(entry.sha256)}`,
            );
        }
    }
    for (const id of pinned.keys()) {
        if (!fixtures.some((fixture) => fixture.id === id)) {
            failures.push(`pin names fixture ${id}, which the generator no longer produces`);
        }
    }
    return failures;
}

const argv = new Set(process.argv.slice(2));
const checkOnly = argv.has("--check");
const update = argv.has("--update");

const fixtures = buildFixtures();
for (const fixture of fixtures) {
    assertDeterministic(fixture);
    assertMixedSyntax(fixture);
}

if (!checkOnly) {
    mkdirSync(OUTPUT_DIR, { recursive: true });
    for (const fixture of fixtures) {
        writeFileSync(join(OUTPUT_DIR, fixture.file), fixture.text, "utf8");
    }
    writeFileSync(
        join(OUTPUT_DIR, "manifest.json"),
        `${JSON.stringify(pinDocument(fixtures), null, 4)}\n`,
        "utf8",
    );
}

if (update) {
    writeFileSync(PIN_PATH, `${JSON.stringify(pinDocument(fixtures), null, 4)}\n`, "utf8");
    console.log(`editor perf fixtures: pin updated at ${PIN_PATH}`);
} else {
    const failures = comparePin(fixtures, readPin());
    if (failures.length > 0) {
        console.error("editor perf fixtures: FAIL");
        for (const failure of failures) console.error(`  - ${failure}`);
        process.exitCode = 1;
    }
}

for (const fixture of fixtures) {
    const profile = fixture.profile;
    console.log(
        `${fixture.id}: ${String(fixture.bytes)} bytes sha256=${fixture.sha256} ` +
            `headings=${String(profile.headings)} callouts=${String(profile.callouts)} ` +
            `mermaid=${String(profile.mermaidFences)} math=${String(profile.blockMath)}/${String(profile.inlineMath)} ` +
            `footnotes=${String(profile.footnoteCalls)}/${String(profile.footnoteDefinitions)} ` +
            `wikilinks=${String(profile.wikilinks)} html=${String(profile.htmlBlocks)}/${String(profile.inlineHtml)} ` +
            `directives=${String(profile.directives)} tableRows=${String(profile.tableRows)} ` +
            `listItems=${String(profile.listItems)} cjk=${String(profile.cjkCharacters)}`,
    );
}

if (process.exitCode === 1) {
    console.error("editor perf fixtures do not match the committed pin");
} else if (!update) {
    console.log("editor perf fixtures: PASS (bytes match the committed pin)");
}
